import { fileURLToPath } from 'node:url';
import tailwindcss from '@tailwindcss/vite';
import { build } from 'vite';

const result = await build({
  configFile: false,
  root: fileURLToPath(new URL('../frontend', import.meta.url)),
  logLevel: 'silent',
  define: { 'process.env.NODE_ENV': JSON.stringify('production') },
  plugins: [tailwindcss()],
  build: {
    write: false,
    minify: true,
    cssMinify: true,
    rolldownOptions: { output: { comments: { legal: true } } },
    lib: {
      entry: fileURLToPath(new URL('../frontend/src/mcp-app/main.tsx', import.meta.url)),
      formats: ['iife'],
      name: 'ContextUsePages',
    },
  },
});
const bundle = Array.isArray(result) ? result[0] : result;
if (!bundle || !('output' in bundle)) {
  throw new Error('Expected one MCP app bundle');
}
const script = bundle.output.find((file) => file.type === 'chunk');
const styles = bundle.output.find(
  (file) => file.type === 'asset' && file.fileName.endsWith('.css'),
);
if (script?.type !== 'chunk' || styles?.type !== 'asset') {
  throw new Error('Expected MCP app script and styles');
}
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Context Use Pages</title><style>${String(styles.source).replaceAll('</style', '<\\/style')}</style></head><body><div id="root"></div><script>${script.code.replaceAll('</script', '<\\/script')}</script></body></html>`;
const destination = Bun.file(
  new URL('../backend/src/routes/mcp/pages/app-html.gen.ts', import.meta.url),
);
const fingerprint = new Bun.CryptoHasher('sha256').update(html).digest('hex');
const generated = `// Generated by bun run generate:mcp-app. Do not edit.\nexport const pagesAppUri = "ui://context-use/workspace-${fingerprint}.html";\nexport const pagesAppHtml = ${JSON.stringify(html)};\n`;
if (Bun.argv.includes('--check')) {
  if (!(await destination.exists()) || (await destination.text()) !== generated) {
    throw new Error('MCP app is stale. Run bun run generate:mcp-app.');
  }
} else {
  await Bun.write(destination, generated);
}
