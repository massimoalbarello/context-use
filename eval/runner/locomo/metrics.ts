import type { LocomoCategory } from "../../data/locomo-v1/dataset.ts";
import { porterStem } from "./porter.ts";

/**
 * Two deterministic LoCoMo scorers, both ported from the code that produced the numbers
 * this repository wants to sit next to.
 *
 * They are not the same function and must not be averaged together. The **official**
 * metric is `snap-research/locomo`'s `eval_question_answering`: a stemmed, article-stripped
 * multiset token F1 with a different rule per category. **A-mem's** is its own
 * `calculate_metrics`: an unstemmed token-*set* F1 plus BLEU and ROUGE, and it is what
 * A-mem's published table reports. Scoring an answer both ways is the only way to put a
 * number beside the benchmark's own results and beside A-mem's without an asterisk on one
 * of them.
 *
 * Both are checked against values generated by the real Python implementations; see
 * `metrics.test.ts` and `data/locomo-v1/metrics-fixture.py`.
 */

// ---------------------------------------------------------------------------
// snap-research/locomo — task_eval/evaluation.py
// ---------------------------------------------------------------------------

const PUNCTUATION = new Set([..."!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~"]);

/**
 * Upstream's `normalize_answer`, in its order: commas out, lowercase, punctuation out,
 * `a`/`an`/`the`/`and` out, whitespace collapsed. `and` is upstream's own addition to the
 * usual SQuAD article list, and it matters for the comma-joined multi-hop answers.
 */
export function normalizeAnswer(value: string): string {
  const lowered = value.replaceAll(",", "").toLowerCase();
  const unpunctuated = [...lowered].filter((character) => !PUNCTUATION.has(character)).join("");
  return unpunctuated.replace(/\b(a|an|the|and)\b/g, " ").split(/\s+/).filter(Boolean).join(" ");
}

function stemmedTokens(value: string): string[] {
  const normalized = normalizeAnswer(value);
  return normalized ? normalized.split(" ").map(porterStem) : [];
}

function counted(tokens: string[]): Map<string, number> {
  const counts = new Map<string, number>();
  for (const token of tokens) counts.set(token, (counts.get(token) ?? 0) + 1);
  return counts;
}

/** Upstream's `f1_score`: multiset overlap of stemmed tokens. */
export function officialF1Score(prediction: string, reference: string): number {
  const predictionTokens = stemmedTokens(prediction);
  const referenceTokens = stemmedTokens(reference);
  const referenceCounts = counted(referenceTokens);
  let same = 0;
  for (const [token, count] of counted(predictionTokens)) {
    same += Math.min(count, referenceCounts.get(token) ?? 0);
  }
  if (same === 0) return 0;
  const precision = same / predictionTokens.length;
  const recall = same / referenceTokens.length;
  return (2 * precision * recall) / (precision + recall);
}

/**
 * Upstream's `f1`, used for multi-hop answers only: both sides are split on commas, and
 * each required sub-answer is credited by its best-matching predicted fragment.
 */
export function officialMultiHopF1(prediction: string, reference: string): number {
  const predictions = prediction.split(",").map((part) => part.trim());
  const references = reference.split(",").map((part) => part.trim());
  const perReference = references.map((entry) =>
    Math.max(...predictions.map((candidate) => officialF1Score(candidate, entry))));
  return perReference.reduce((total, value) => total + value, 0) / perReference.length;
}

/** Upstream's adversarial rule: credit is for declining, whatever the reference says. */
export function officialAdversarialScore(prediction: string): number {
  const lowered = prediction.toLowerCase();
  return lowered.includes("no information available") || lowered.includes("not mentioned") ? 1 : 0;
}

/**
 * The reference an answer is actually scored against.
 *
 * Category 3 truncates at the first semicolon because upstream's open-domain answers list
 * alternatives there and it scores only the first.
 */
export function officialReference(reference: string, category: LocomoCategory): string {
  return category === 3 ? (reference.split(";")[0] ?? "").trim() : reference;
}

/** One row of upstream's `eval_question_answering`, for one question. */
export function officialScore(
  prediction: string,
  reference: string,
  category: LocomoCategory,
): number {
  if (category === 5) return officialAdversarialScore(prediction);
  const target = officialReference(reference, category);
  if (category === 1) return officialMultiHopF1(prediction, target);
  return officialF1Score(prediction, target);
}

