/**
 * NLTK's Porter stemmer, ported.
 *
 * Both LoCoMo scorers this repository reproduces stem before comparing tokens — the
 * official one through `nltk.stem.PorterStemmer`, A-mem's ROUGE through `rouge_score`'s
 * use of the same class — so the stemmer is part of the metric rather than a detail
 * underneath it. A stem that differs from NLTK's by one word moves every F1 that word
 * appears in, silently and in an unknown direction.
 *
 * This is NLTK's default `NLTK_EXTENSIONS` mode, not Martin Porter's original: the
 * irregular-form pool, the `ies`/`ied` short-word rules, the consonant-only `y -> i`
 * condition, and the `fulli` and `logi` rules are all NLTK's departures from the 1980
 * algorithm, and all of them are what `ps.stem` actually does upstream.
 *
 * `porter.test.ts` checks this against stems generated by the real NLTK class, so the port
 * is verified rather than asserted. Regenerate that fixture with
 * `data/locomo-v1/metrics-fixture.py`.
 */

/** Words NLTK stems by table because the rules get them wrong. */
const IRREGULAR: Record<string, string> = {
  sky: "sky",
  skies: "sky",
  dying: "die",
  lying: "lie",
  tying: "tie",
  news: "news",
  innings: "inning",
  inning: "inning",
  outings: "outing",
  outing: "outing",
  cannings: "canning",
  canning: "canning",
  howe: "howe",
  proceed: "proceed",
  exceed: "exceed",
  succeed: "succeed",
};

const VOWELS = new Set(["a", "e", "i", "o", "u"]);

function isConsonant(word: string, index: number): boolean {
  const letter = word[index];
  if (letter === undefined || VOWELS.has(letter)) return false;
  if (letter === "y") return index === 0 ? true : !isConsonant(word, index - 1);
  return true;
}

/** Porter's `m`: the number of vowel-consonant sequences in a stem. */
function measure(stem: string): number {
  let sequence = "";
  for (let index = 0; index < stem.length; index += 1) {
    sequence += isConsonant(stem, index) ? "c" : "v";
  }
  return sequence.split("vc").length - 1;
}

function hasPositiveMeasure(stem: string): boolean {
  return measure(stem) > 0;
}

function containsVowel(stem: string): boolean {
  for (let index = 0; index < stem.length; index += 1) {
    if (!isConsonant(stem, index)) return true;
  }
  return false;
}

function endsDoubleConsonant(word: string): boolean {
  return word.length >= 2
    && word[word.length - 1] === word[word.length - 2]
    && isConsonant(word, word.length - 1);
}

function endsCvc(word: string): boolean {
  const classic = word.length >= 3
    && isConsonant(word, word.length - 3)
    && !isConsonant(word, word.length - 2)
    && isConsonant(word, word.length - 1)
    && !["w", "x", "y"].includes(word[word.length - 1]!);
  // NLTK's extension, which is why `hop` and `at` do not stem alike.
  const nltk = word.length === 2 && !isConsonant(word, 0) && isConsonant(word, 1);
  return classic || nltk;
}

function replaceSuffix(word: string, suffix: string, replacement: string): string {
  if (suffix === "") return word + replacement;
  return word.slice(0, word.length - suffix.length) + replacement;
}

type Rule = [suffix: string, replacement: string, condition: ((stem: string) => boolean) | null];

/**
 * The first rule whose suffix matches decides the outcome, including when its condition
 * fails — a failed condition returns the word untouched rather than falling through to the
 * next rule. Getting that wrong is the classic way a Porter port drifts.
 */
function applyRules(word: string, rules: Rule[]): string {
  for (const [suffix, replacement, condition] of rules) {
    if (suffix === "*d" && endsDoubleConsonant(word)) {
      // Both consonants come off and the rule puts one back, so `hopp` becomes `hop`.
      const stem = word.slice(0, -2);
      return !condition || condition(stem) ? stem + replacement : word;
    }
    if (suffix !== "*d" && word.endsWith(suffix)) {
      const stem = replaceSuffix(word, suffix, "");
      return !condition || condition(stem) ? stem + replacement : word;
    }
  }
  return word;
}

function step1a(word: string): string {
  if (word.endsWith("ies") && word.length === 4) return replaceSuffix(word, "ies", "ie");
  return applyRules(word, [
    ["sses", "ss", null],
    ["ies", "i", null],
    ["ss", "ss", null],
    ["s", "", null],
  ]);
}

function step1b(word: string): string {
  if (word.endsWith("ied")) {
    return word.length === 4 ? replaceSuffix(word, "ied", "ie") : replaceSuffix(word, "ied", "i");
  }
  if (word.endsWith("eed")) {
    const stem = replaceSuffix(word, "eed", "");
    return measure(stem) > 0 ? `${stem}ee` : word;
  }
  let intermediate: string | undefined;
  for (const suffix of ["ed", "ing"]) {
    if (word.endsWith(suffix)) {
      const candidate = replaceSuffix(word, suffix, "");
      if (containsVowel(candidate)) {
        intermediate = candidate;
        break;
      }
    }
  }
  if (intermediate === undefined) return word;
  const last = intermediate[intermediate.length - 1] ?? "";
  return applyRules(intermediate, [
    ["at", "ate", null],
    ["bl", "ble", null],
    ["iz", "ize", null],
    ["*d", last, () => !["l", "s", "z"].includes(last)],
    ["", "e", (stem) => measure(stem) === 1 && endsCvc(stem)],
  ]);
}

function step1c(word: string): string {
  // NLTK's condition: `y -> i` only after a consonant, and never for a bare consonant
  // stem, so `happy` stems to `happi` while `enjoy` is left alone.
  return applyRules(word, [
    ["y", "i", (stem) => stem.length > 1 && isConsonant(stem, stem.length - 1)],
  ]);
}

function step2(word: string): string {
  if (word.endsWith("alli") && hasPositiveMeasure(replaceSuffix(word, "alli", ""))) {
    return step2(replaceSuffix(word, "alli", "al"));
  }
  return applyRules(word, [
    ["ational", "ate", hasPositiveMeasure],
    ["tional", "tion", hasPositiveMeasure],
    ["enci", "ence", hasPositiveMeasure],
    ["anci", "ance", hasPositiveMeasure],
    ["izer", "ize", hasPositiveMeasure],
    ["bli", "ble", hasPositiveMeasure],
    ["alli", "al", hasPositiveMeasure],
    ["entli", "ent", hasPositiveMeasure],
    ["eli", "e", hasPositiveMeasure],
    ["ousli", "ous", hasPositiveMeasure],
    ["ization", "ize", hasPositiveMeasure],
    ["ation", "ate", hasPositiveMeasure],
    ["ator", "ate", hasPositiveMeasure],
    ["alism", "al", hasPositiveMeasure],
    ["iveness", "ive", hasPositiveMeasure],
    ["fulness", "ful", hasPositiveMeasure],
    ["ousness", "ous", hasPositiveMeasure],
    ["aliti", "al", hasPositiveMeasure],
    ["iviti", "ive", hasPositiveMeasure],
    ["biliti", "ble", hasPositiveMeasure],
    ["fulli", "ful", hasPositiveMeasure],
    // The `l` goes with the stem, so short stems such as `geo` and `theo` behave like
    // `archaeo` and `philo`.
    ["logi", "log", () => hasPositiveMeasure(word.slice(0, -3))],
  ]);
}

function step3(word: string): string {
  return applyRules(word, [
    ["icate", "ic", hasPositiveMeasure],
    ["ative", "", hasPositiveMeasure],
    ["alize", "al", hasPositiveMeasure],
    ["iciti", "ic", hasPositiveMeasure],
    ["ical", "ic", hasPositiveMeasure],
    ["ful", "", hasPositiveMeasure],
    ["ness", "", hasPositiveMeasure],
  ]);
}

function step4(word: string): string {
  const measureOverOne = (stem: string): boolean => measure(stem) > 1;
  return applyRules(word, [
    ["al", "", measureOverOne],
    ["ance", "", measureOverOne],
    ["ence", "", measureOverOne],
    ["er", "", measureOverOne],
    ["ic", "", measureOverOne],
    ["able", "", measureOverOne],
    ["ible", "", measureOverOne],
    ["ant", "", measureOverOne],
    ["ement", "", measureOverOne],
    ["ment", "", measureOverOne],
    ["ent", "", measureOverOne],
    ["ion", "", (stem) => measure(stem) > 1 && ["s", "t"].includes(stem[stem.length - 1] ?? "")],
    ["ou", "", measureOverOne],
    ["ism", "", measureOverOne],
    ["ate", "", measureOverOne],
    ["iti", "", measureOverOne],
    ["ous", "", measureOverOne],
    ["ive", "", measureOverOne],
    ["ize", "", measureOverOne],
  ]);
}

function step5a(word: string): string {
  if (!word.endsWith("e")) return word;
  const stem = word.slice(0, -1);
  if (measure(stem) > 1) return stem;
  if (measure(stem) === 1 && !endsCvc(stem)) return stem;
  return word;
}

function step5b(word: string): string {
  return applyRules(word, [["ll", "l", () => measure(word.slice(0, -1)) > 1]]);
}

export function porterStem(word: string): string {
  const lowered = word.toLowerCase();
  const irregular = IRREGULAR[lowered];
  if (irregular !== undefined) return irregular;
  // NLTK returns words of two letters or fewer unchanged in its extension modes.
  if (lowered.length <= 2) return lowered;
  return step5b(step5a(step4(step3(step2(step1c(step1b(step1a(lowered))))))));
}
